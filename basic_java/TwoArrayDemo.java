public class TwoArrayDemo {
    public static void main(String[] args) {
        int arr[][]={{11,22,33},{66,99,100},{38,90,28}};
        for(int i=0;i<3;i++)
        {
            for (int j=0;j<3;j++)
            {
                System.out.print(" "+arr[i][j]);
            }System.out.println();
        }
    }
}
